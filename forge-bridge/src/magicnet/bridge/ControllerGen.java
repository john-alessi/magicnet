package magicnet.bridge;

import java.io.File;
import java.io.PrintWriter;
import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/**
 * Generates GeneratedController.java by reflecting over PlayerControllerAi.
 *
 * Hand-writing 111 overrides would be both tedious and brittle across Forge
 * versions. This reflects the live class on the classpath, so the generated
 * controller always matches the jar it was built against. Re-run after a Forge
 * upgrade and the compiler will tell you if anything moved.
 *
 * Every override is pass-through: it times the super call, records it, and
 * returns Forge's own answer unchanged. Game outcomes are therefore identical
 * to an unmodified AI-vs-AI run.
 */
public final class ControllerGen {

    /** Accessors and bookkeeping, not decisions. Overriding these would be noise. */
    private static final Set<String> SKIP = new HashSet<>(Arrays.asList(
            "isAI", "getGame", "getMatch", "getPlayer", "getLobbyPlayer", "getAi",
            "getGameView", "getView", "tempShowCards", "endTempShowCards",
            "equals", "hashCode", "toString", "getClass", "notify", "notifyAll", "wait",
            "setFullControl", "isFullControl", "getFullControl", "clearFullControls",
            "allowFullControl", "setUseSimulation", "initializeView", "setPlayer",
            "onCardRemovedFromZone", "resetAtEndOfTurn",

            // Hand-instrumented in InstrumentedController because the generic
            // pass-through cannot see its branching factor: it takes no arguments,
            // so the candidate set has to be reconstructed explicitly.
            "chooseSpellAbilityToPlay"
    ));

    public static void main(String[] args) throws Exception {
        File outFile = new File(args.length > 0
                ? args[0]
                : "src/magicnet/bridge/GeneratedController.java");
        outFile.getParentFile().mkdirs();

        Class<?> base = Class.forName("forge.ai.PlayerControllerAi");
        Class<?> root = Class.forName("forge.game.player.PlayerController");

        List<Method> methods = new ArrayList<>();
        Set<String> seen = new HashSet<>();

        for (Method m : base.getMethods()) {
            Class<?> dc = m.getDeclaringClass();
            if (dc != base && dc != root) {
                continue;
            }
            int mod = m.getModifiers();
            if (Modifier.isStatic(mod) || Modifier.isFinal(mod)) {
                continue;
            }
            if (m.isBridge() || m.isSynthetic()) {
                continue;
            }
            if (SKIP.contains(m.getName())) {
                continue;
            }
            String sig = signatureKey(m);
            if (!seen.add(sig)) {
                continue;
            }
            methods.add(m);
        }

        methods.sort(Comparator.comparing(Method::getName)
                .thenComparingInt(Method::getParameterCount));

        try (PrintWriter w = new PrintWriter(outFile, "UTF-8")) {
            w.println("package magicnet.bridge;");
            w.println();
            w.println("// GENERATED by magicnet.bridge.ControllerGen -- do not edit by hand.");
            w.println("// Regenerate after any Forge upgrade:  ./build.sh");
            w.println("//");
            w.println("// " + methods.size() + " PlayerController callbacks instrumented.");
            w.println("//");
            w.println("// Each override is a pure pass-through to Forge's own AI. Behaviour is");
            w.println("// unchanged; we only observe. Replace a super call with your own policy to");
            w.println("// take over that decision type.");
            w.println("public class GeneratedController extends forge.ai.PlayerControllerAi {");
            w.println();
            w.println("    public GeneratedController(forge.game.Game game, "
                    + "forge.game.player.Player p, forge.LobbyPlayer lp) {");
            w.println("        super(game, p, lp);");
            w.println("    }");

            for (Method m : methods) {
                emit(w, m);
            }

            w.println("}");
        }

        System.out.println("Generated " + outFile.getPath() + " with " + methods.size() + " overrides.");

        // Report what we deliberately skipped, so the exclusion list stays honest.
        List<String> skipped = new ArrayList<>();
        for (Method m : base.getMethods()) {
            Class<?> dc = m.getDeclaringClass();
            if (dc != base && dc != root) {
                continue;
            }
            if (Modifier.isFinal(m.getModifiers()) && !SKIP.contains(m.getName())) {
                skipped.add(m.getName() + "/" + m.getParameterCount() + " (final)");
            }
        }
        if (!skipped.isEmpty()) {
            System.out.println("Not overridable (final in Forge): " + String.join(", ", skipped));
        }
    }

    private static String signatureKey(Method m) {
        StringBuilder sb = new StringBuilder(m.getName());
        for (Class<?> p : m.getParameterTypes()) {
            sb.append('|').append(p.getName());
        }
        return sb.toString();
    }

    private static void emit(PrintWriter w, Method m) {
        String name = m.getName();
        int arity = m.getParameterCount();
        String key = name + "/" + arity;

        Type[] params = m.getGenericParameterTypes();
        Type ret = m.getGenericReturnType();
        boolean isVoid = ret == void.class;

        StringBuilder decl = new StringBuilder();
        decl.append("    @Override public ");
        String tp = typeParams(m);
        if (!tp.isEmpty()) {
            decl.append(tp);
        }
        decl.append(typeName(ret)).append(' ').append(name).append('(');
        for (int i = 0; i < params.length; i++) {
            if (i > 0) {
                decl.append(", ");
            }
            decl.append(typeName(params[i])).append(" a").append(i);
        }
        decl.append(')');

        Class<?>[] exceptions = m.getExceptionTypes();
        if (exceptions.length > 0) {
            decl.append(" throws ");
            for (int i = 0; i < exceptions.length; i++) {
                if (i > 0) {
                    decl.append(", ");
                }
                decl.append(exceptions[i].getCanonicalName());
            }
        }
        decl.append(" {");

        w.println();
        w.println(decl);
        w.println("        long t0 = System.nanoTime();");
        w.println("        try {");
        if (isVoid) {
            w.println("            super." + name + "(" + argList(arity) + ");");
        } else {
            w.println("            return super." + name + "(" + argList(arity) + ");");
        }
        w.println("        } finally {");
        w.println("            magicnet.bridge.DecisionLog.record(\"" + key
                + "\", t0, getPlayer(), " + argArray(arity) + ");");
        w.println("        }");
        w.println("    }");
    }

    private static String argList(int n) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < n; i++) {
            if (i > 0) {
                sb.append(", ");
            }
            sb.append('a').append(i);
        }
        return sb.toString();
    }

    private static String argArray(int n) {
        if (n == 0) {
            return "null";
        }
        StringBuilder sb = new StringBuilder("new Object[]{");
        for (int i = 0; i < n; i++) {
            if (i > 0) {
                sb.append(", ");
            }
            sb.append('a').append(i);
        }
        return sb.append('}').toString();
    }

    private static String typeParams(Method m) {
        TypeVariable<Method>[] tvs = m.getTypeParameters();
        if (tvs.length == 0) {
            return "";
        }
        StringBuilder sb = new StringBuilder("<");
        for (int i = 0; i < tvs.length; i++) {
            if (i > 0) {
                sb.append(", ");
            }
            sb.append(tvs[i].getName());
            Type[] bounds = tvs[i].getBounds();
            if (bounds.length > 0 && !bounds[0].equals(Object.class)) {
                sb.append(" extends ").append(typeName(bounds[0]));
            }
        }
        return sb.append("> ").toString();
    }

    private static String typeName(Type t) {
        if (t instanceof Class<?> c) {
            String n = c.getCanonicalName();
            return n != null ? n : c.getName();
        }
        if (t instanceof ParameterizedType p) {
            StringBuilder sb = new StringBuilder(typeName(p.getRawType()));
            Type[] a = p.getActualTypeArguments();
            if (a.length > 0) {
                sb.append('<');
                for (int i = 0; i < a.length; i++) {
                    if (i > 0) {
                        sb.append(", ");
                    }
                    sb.append(typeName(a[i]));
                }
                sb.append('>');
            }
            return sb.toString();
        }
        if (t instanceof GenericArrayType g) {
            return typeName(g.getGenericComponentType()) + "[]";
        }
        if (t instanceof TypeVariable<?> v) {
            return v.getName();
        }
        if (t instanceof WildcardType wc) {
            Type[] lower = wc.getLowerBounds();
            if (lower.length > 0) {
                return "? super " + typeName(lower[0]);
            }
            Type[] upper = wc.getUpperBounds();
            if (upper.length > 0 && !upper[0].equals(Object.class)) {
                return "? extends " + typeName(upper[0]);
            }
            return "?";
        }
        return t.getTypeName();
    }
}
