package magicnet.bridge;

import java.lang.reflect.Field;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Collections;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Pattern;

import forge.card.CardStateName;
import forge.game.CardTraitBase;
import forge.game.card.Card;
import forge.game.card.CardState;
import forge.game.card.ICardTraitChanges;
import forge.game.keyword.Keyword;
import forge.game.keyword.KeywordInterface;
import forge.game.player.Player;
import forge.game.replacement.ReplacementEffect;
import forge.game.spellability.SpellAbility;
import forge.game.staticability.StaticAbility;
import forge.game.trigger.Trigger;

/**
 * The engine-resolved ability difference of a battlefield object from its
 * printed card (schema 10): {@code gained} and {@code lost}.
 *
 * <p>Keywords have no special status: they are shorthand for rules text, and
 * the printed abilities already reach the model through {@code oracle_id}. So
 * an object carries only what differs. Both sides are sets of normalized rules
 * text; {@code gained = current - printed}, {@code lost = printed - current}.
 * "Loses all abilities" (Humility, Dress Down) is reported as every printed
 * ability, one entry each, not as a summary token.
 *
 * <p><b>Printed</b> is the current {@link CardState}'s own traits before any
 * card-level change: its intrinsic keywords and its intrinsic triggers,
 * statics, replacements and activated abilities (read from the state's fields;
 * Forge has no public getter for the pre-change list). The current state is
 * used so a face-down object compares against its face-down (blank) state and
 * a copy against what it copies. <b>Current</b> is what Forge reports after
 * all changes: {@code getKeywords()}, {@code getHiddenExtrinsicKeywords()},
 * and the state's change-applied trait lists.
 *
 * <p>Text normalization, so that one grant renders identically on any host:
 * <ul>
 *   <li>keywords are their plain keyword text ({@code getTitle()}, e.g.
 *       "Flying", "Ward {2}"); other traits are their raw rules description
 *       ({@code TriggerDescription} / {@code Description} / cost plus
 *       {@code SpellDescription} along the sub-ability chain), never Forge's
 *       rendered {@code toString()}, which substitutes the host's name;</li>
 *   <li>{@code CARDNAME}/{@code NICKNAME} and the host's own name (whole
 *       word; not for tokens or basic lands, whose names are type words) become
 *       "this creature" (host currently a creature) or "this permanent";
 *       {@code ORIGINALHOST}/{@code EFFECTSOURCE} become "the source";</li>
 *   <li>a leading {@code HIDDEN } marker is dropped, object ids
 *       {@code " (123)"} and any {@code "Activator: ..."} tail are removed,
 *       player names become "that player", whitespace is collapsed.</li>
 * </ul>
 *
 * <p>Filtered out, on both sides (documented, not abilities in their own
 * right):
 * <ul>
 *   <li>engine plumbing encoded as an UNDEFINED keyword containing ':'
 *       ({@code ETBReplacement:...}, {@code etbCounter:...}) -- its effect is
 *       visible elsewhere (counters, chosen_type);</li>
 *   <li>traits generated by a keyword -- the keyword text stands for them;</li>
 *   <li>the casting/playing abilities of the card itself (spell, land play);</li>
 *   <li>type-intrinsic traits Forge synthesizes from the current type line
 *       (basic land mana abilities, loyalty/defense/lore ETB counters) --
 *       {@code types} already carries them;</li>
 *   <li>suppressed traits and traits with no rules description (effect
 *       bookkeeping such as AI hints).</li>
 * </ul>
 */
final class AbilityText {

    static final class Diff {
        final List<String> gained;
        final List<String> lost;

        Diff(List<String> gained, List<String> lost) {
            this.gained = gained;
            this.lost = lost;
        }
    }

    private static final Pattern OBJECT_ID = Pattern.compile("\\s*\\(\\d+\\)");
    private static final Pattern ACTIVATOR = Pattern.compile("\\s*Activator:.*$");
    private static final Pattern SPACE = Pattern.compile("\\s+");

    private AbilityText() {
    }

    static Diff of(Card c) {
        CardState state = c.getCurrentState();
        String self = c.isCreature() ? "this creature" : "this permanent";
        Set<CardTraitBase> typeIntrinsic = typeIntrinsic(state);

        TreeSet<String> printed = new TreeSet<>();
        for (KeywordInterface ki : state.getIntrinsicKeywords()) {
            add(printed, keywordText(ki), c, self);
        }
        for (CardState s : withSplitHalves(state)) {
            for (String f : new String[] {"abilities", "triggers", "replacementEffects", "staticAbilities"}) {
                for (Object o : rawTraits(s, f)) {
                    CardTraitBase tb = (CardTraitBase) o;
                    if (tb.isIntrinsic()) {
                        add(printed, traitText(tb, typeIntrinsic), c, self);
                    }
                }
            }
        }

        TreeSet<String> current = new TreeSet<>();
        for (KeywordInterface ki : c.getKeywords()) {
            add(current, keywordText(ki), c, self);
        }
        for (String hidden : c.getHiddenExtrinsicKeywords()) {
            add(current, hidden, c, self);
        }
        List<CardTraitBase> traits = new ArrayList<>();
        traits.addAll(state.getSpellAbilities());
        traits.addAll(state.getTriggers());
        traits.addAll(state.getStaticAbilities());
        // rulesHost=false: shield/stun counter replacements are counters, not abilities.
        traits.addAll(state.getReplacementEffects(false));
        for (CardTraitBase tb : traits) {
            add(current, traitText(tb, typeIntrinsic), c, self);
        }

        TreeSet<String> gained = new TreeSet<>(current);
        gained.removeAll(printed);
        TreeSet<String> lost = new TreeSet<>(printed);
        lost.removeAll(current);
        return new Diff(new ArrayList<>(gained), new ArrayList<>(lost));
    }

    /** The same split-card halves Forge folds into an Original state's trait lists. */
    private static List<CardState> withSplitHalves(CardState state) {
        List<CardState> out = new ArrayList<>();
        out.add(state);
        Card c = state.getCard();
        if (state.getStateName() == CardStateName.Original) {
            for (CardStateName half : new CardStateName[] {CardStateName.LeftSplit, CardStateName.RightSplit}) {
                if (c.hasState(half)) {
                    out.add(c.getState(half));
                }
            }
        }
        return out;
    }

    private static Collection<?> rawTraits(CardState s, String field) {
        try {
            Field f = CardState.class.getDeclaredField(field);
            f.setAccessible(true);
            Object v = f.get(s);
            return v instanceof Collection ? (Collection<?>) v : Collections.emptyList();
        } catch (ReflectiveOperationException | RuntimeException e) {
            return Collections.emptyList();
        }
    }

    /** Traits Forge derives from the current type line (CardState.LandTraitChanges). */
    private static Set<CardTraitBase> typeIntrinsic(CardState state) {
        Set<CardTraitBase> out = Collections.newSetFromMap(new IdentityHashMap<>());
        try {
            for (Object o : state.getLandTraitChanges()) {
                ICardTraitChanges ltc = (ICardTraitChanges) o;
                out.addAll(ltc.applySpellAbility(new ArrayList<>()));
                out.addAll(ltc.applyReplacementEffect(new ArrayList<>()));
            }
        } catch (RuntimeException ignored) {
            // nothing excluded
        }
        return out;
    }

    static String keywordText(KeywordInterface ki) {
        if (ki.getKeyword() == Keyword.UNDEFINED
                && ki.getOriginal() != null && ki.getOriginal().contains(":")) {
            return null;
        }
        String s = ki.getTitle();
        if (s == null || s.isEmpty()) {
            s = ki.getOriginal();
        }
        return s;
    }

    private static String traitText(CardTraitBase tb, Set<CardTraitBase> typeIntrinsic) {
        if (tb == null || tb.getKeyword() != null || tb.isSuppressed() || typeIntrinsic.contains(tb)) {
            return null;
        }
        if (tb instanceof SpellAbility) {
            SpellAbility sa = (SpellAbility) tb;
            if (sa.isSpell() || sa.isLandAbility()) {
                return null;
            }
            StringBuilder sb = new StringBuilder();
            for (SpellAbility node = sa; node != null; node = node.getSubAbility()) {
                String d = node.getDescription();
                if (d != null && !d.isEmpty()) {
                    if (sb.length() > 0) {
                        sb.append(' ');
                    }
                    sb.append(d);
                }
            }
            return sb.toString();
        }
        if (tb instanceof Trigger) {
            return tb.getParamOrDefault("TriggerDescription", null);
        }
        if (tb instanceof StaticAbility || tb instanceof ReplacementEffect) {
            return tb.getParamOrDefault("Description", null);
        }
        return null;
    }

    private static void add(Set<String> out, String raw, Card host, String self) {
        String s = normalize(raw, host, self);
        if (s != null) {
            out.add(s);
        }
    }

    static String normalize(String raw, Card host, String self) {
        if (raw == null) {
            return null;
        }
        String s = raw.trim();
        if (s.startsWith("HIDDEN ")) {
            s = s.substring(7);
        }
        s = s.replace("CARDNAME", self).replace("NICKNAME", self)
                .replace("ORIGINALHOST", "the source").replace("EFFECTSOURCE", "the source");
        // Token and basic land names are type words ("Spirit", "Treasure",
        // "Island") that legitimately appear in other rules text.
        String name = host.isFaceDown() || host.isToken() || host.isBasicLand() ? null : host.getName();
        if (name != null && !name.isEmpty()) {
            s = Pattern.compile("\\b" + Pattern.quote(name) + "\\b").matcher(s)
                    .replaceAll(java.util.regex.Matcher.quoteReplacement(self));
        }
        try {
            for (Player p : host.getGame().getRegisteredPlayers()) {
                String pn = p.getName();
                if (pn != null && !pn.isEmpty()) {
                    s = s.replace(pn, "that player");
                }
            }
        } catch (RuntimeException ignored) {
            // no game
        }
        s = OBJECT_ID.matcher(s).replaceAll("");
        s = ACTIVATOR.matcher(s).replaceAll("");
        s = SPACE.matcher(s).replaceAll(" ").trim();
        if (!s.isEmpty() && Character.isLowerCase(s.charAt(0)) && s.startsWith("this ")) {
            s = "T" + s.substring(1);
        }
        return s.isEmpty() ? null : s;
    }
}
