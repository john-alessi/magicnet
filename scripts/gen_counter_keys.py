"""Regenerate src/magicnet/catalog/counter_keys.json from Forge's counter types.

    uv run python scripts/gen_counter_keys.py            # write the file
    uv run python scripts/gen_counter_keys.py --check    # exit 1 if it is stale

Compiles scripts/counter_keys/CounterKeys.java against the Forge jar and runs it.
The bridge emits counters as ``"ctr_" + getName().toLowerCase()`` (see
StateExtractor.addCounters); the Java program prints exactly that key, so the
list is Forge's own, not a hand transcription.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "scripts" / "counter_keys" / "CounterKeys.java"
OUT = REPO / "src" / "magicnet" / "catalog" / "counter_keys.json"
FORGE_JAR = Path(os.environ.get("MAGICNET_FORGE_JAR", "/usr/share/java/forge-gui-desktop.jar"))


def forge_counter_types(classes_dir: Path | None = None) -> list[dict]:
    """Every Forge CounterType, as {key, name, display, enum, keyword}."""
    classes = classes_dir or REPO / "scripts" / "counter_keys" / "classes"
    classes.mkdir(parents=True, exist_ok=True)
    try:
        subprocess.run(["javac", "-cp", str(FORGE_JAR), "-d", str(classes), str(SOURCE)],
                       check=True, capture_output=True, text=True, timeout=120)
        proc = subprocess.run(["java", "-cp", f"{classes}:{FORGE_JAR}", "CounterKeys"],
                              check=True, capture_output=True, text=True, timeout=120)
    finally:
        if classes_dir is None:
            shutil.rmtree(classes, ignore_errors=True)
    return [json.loads(line) for line in proc.stdout.splitlines() if line.startswith("{")]


def render(counters: list[dict]) -> str:
    body = ",\n".join("    " + json.dumps(c, ensure_ascii=False) for c in counters)
    return (
        "{\n"
        '  "about": "Generated by scripts/gen_counter_keys.py from forge.game.card.CounterType.getValues(); do not edit.",\n'
        f'  "forge_jar": {json.dumps(FORGE_JAR.name)},\n'
        f'  "count": {len(counters)},\n'
        '  "counters": [\n' + body + "\n  ]\n}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with the committed file instead of writing")
    args = ap.parse_args()
    text = render(forge_counter_types())
    if args.check:
        stale = not OUT.exists() or OUT.read_text() != text
        print(f"{OUT} is {'STALE' if stale else 'up to date'}")
        return 1 if stale else 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({text.count(chr(10) + '    {')} counters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
